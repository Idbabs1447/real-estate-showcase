/** Distinct districts, derived from the data so filters never go stale. */
export const districts = Array.from(new Set(properties.map((p) => p.district))).sort();

export const intents: { value: Intent | "all"; label: string }[] = [
  { value: "all", label: "Buy or rent" },
  { value: "sale", label: "For sale" },
  { value: "rent", label: "To let" },
];

export function getProperty(id: string): Property | undefined {
  return properties.find((p) => p.id === id);
}

export function getAdvisor(id: string) {
  return advisors.find((a) => a.id === id) ?? advisors[0];
}

export function similarProperties(property: Property, limit = 3): Property[] {
  return properties
    .filter((p) => p.id !== property.id)
    .map((p) => {
      let score = 0;
      if (p.intent === property.intent) score += 3;
      if (p.type === property.type) score += 2;
      if (p.district === property.district) score += 2;
      if (p.region === property.region) score += 1;
      if (p.bedrooms === property.bedrooms) score += 1;
      const ratio = p.price / property.price;
      if (ratio > 0.6 && ratio < 1.7) score += 2;
      return { p, score };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.p);
}
